"""
ingest/sinks.py
───────────────
Where ingested bundles land.

Two sinks, deliberately identical in output shape:

  LocalBundleSink   writes  <out_dir>/<sheet_id>/core__<Tab>.json
                    byte-identical in structure to fetcher/satellite_bundle_fetcher.py,
                    so assayer/smoke_assay.py runs on API data with no changes.

  SupabaseSink      upserts satellite_tab_snapshots on (sheet_id, tab_name),
                    the same table the sheets bridge writes to.  Everything
                    downstream (brain/, assayer/, the dashboard) reads that
                    table and cannot tell the difference.

Safety: the Supabase sink is inert unless explicitly selected AND credentials
are present.  Nothing in this repo writes to production Supabase by accident.
"""

from __future__ import annotations

import json
import logging
import os
import urllib.error
import urllib.parse
import urllib.request
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

from ingest.models import IngestBundle

log = logging.getLogger("ingest.sink")

BRIDGE_VERSION = "api-ingest-v1"


def utc_now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


# ─────────────────────────────────────────────────────────────────────────
# Local bundle sink
# ─────────────────────────────────────────────────────────────────────────

class LocalBundleSink:
    """
    Writes the exact on-disk layout the existing Assayer tooling already reads.

        <root>/<satellite_id>/manifest.json
        <root>/<satellite_id>/core__UpcomingClean.json
        <root>/<satellite_id>/core__ResultsClean.json
        ...
    """

    name = "local"

    def __init__(self, root: str | Path = "ingest/out"):
        self.root = Path(root)

    def write(self, bundle: IngestBundle) -> Dict[str, Any]:
        out_dir = self.root / _safe(bundle.satellite_id)
        out_dir.mkdir(parents=True, exist_ok=True)

        written: List[str] = []
        for tab_name, values in bundle.tabs.items():
            key = f"core::{tab_name}"
            payload = {
                "requested_range": f"'{tab_name}'",
                "returned_range": f"'{tab_name}'",
                "key": key,
                "values": values,
            }
            (out_dir / f"{key.replace('::', '__')}.json").write_text(
                json.dumps(payload, indent=1), encoding="utf-8"
            )
            written.append(key)

        manifest = {
            "spreadsheet_id": bundle.satellite_id,
            "title": bundle.satellite_name,
            "fetched_at": utc_now_iso(),
            "tabs_total": len(bundle.tabs),
            "core_tabs_selected": {t: t for t in bundle.tabs},
            "pattern_tabs_selected_counts": {},
            "dims": {},
            "ranges_count": len(bundle.tabs),
            "source": "api-ingest",
            "provenance": bundle.meta,
            "notes": "Generated by ingest/ — no Google Sheets involved.",
        }
        (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
        return {"sink": self.name, "dir": str(out_dir), "tabs": written}


# ─────────────────────────────────────────────────────────────────────────
# Supabase sink
# ─────────────────────────────────────────────────────────────────────────

class SupabaseSink:
    """
    Upserts into the existing `satellite_tab_snapshots` table via PostgREST.

    Uses stdlib urllib rather than supabase-py so ingestion adds no dependency
    and can run in a GitHub Action with nothing but env vars.

    Requires (env):
        SUPABASE_URL
        SUPABASE_SERVICE_KEY
    """

    name = "supabase"

    def __init__(
        self,
        url: Optional[str] = None,
        service_key: Optional[str] = None,
        table: str = "satellite_tab_snapshots",
        bridge_version: str = BRIDGE_VERSION,
        dry_run: bool = False,
    ):
        self.url = (url or os.environ.get("SUPABASE_URL", "")).rstrip("/")
        self.service_key = service_key or os.environ.get("SUPABASE_SERVICE_KEY", "")
        self.table = table
        self.bridge_version = bridge_version
        self.dry_run = dry_run

    @property
    def configured(self) -> bool:
        return bool(self.url) and bool(self.service_key) and not self.url.startswith("<")

    def _post(self, path: str, payload: Any, prefer: str = "") -> Any:
        if not self.configured:
            raise RuntimeError(
                "Supabase sink not configured — set SUPABASE_URL and SUPABASE_SERVICE_KEY, "
                "or use --sink local"
            )
        req = urllib.request.Request(
            f"{self.url}/rest/v1/{path}",
            data=json.dumps(payload).encode("utf-8"),
            method="POST",
            headers={
                "apikey": self.service_key,
                "Authorization": f"Bearer {self.service_key}",
                "Content-Type": "application/json",
                "Prefer": prefer or "resolution=merge-duplicates,return=minimal",
            },
        )
        with urllib.request.urlopen(req, timeout=45) as resp:
            body = resp.read().decode("utf-8")
        return json.loads(body) if body.strip() else None

    def write(self, bundle: IngestBundle) -> Dict[str, Any]:
        rows = [
            {
                "sheet_id": bundle.satellite_id,
                "tab_name": tab_name,
                "values_json": values,
                "row_count": len(values),
                "col_count": len(values[0]) if values else 0,
                "bridge_version": self.bridge_version,
                "last_mirrored_at": utc_now_iso(),
            }
            for tab_name, values in bundle.tabs.items()
        ]

        if self.dry_run:
            log.info("[dry-run] would upsert %d snapshot rows for %s", len(rows), bundle.satellite_id)
            return {"sink": self.name, "dry_run": True, "rows": len(rows), "satellite_id": bundle.satellite_id}

        # on_conflict targets the uq_snapshot_sheet_tab constraint added by
        # supabase/migrations/20250601_mirror_schema.sql
        self._post(
            f"{self.table}?on_conflict=sheet_id,tab_name",
            rows,
            prefer="resolution=merge-duplicates,return=minimal",
        )
        self._record_sync_event(bundle)
        return {"sink": self.name, "rows": len(rows), "satellite_id": bundle.satellite_id}

    def _record_sync_event(self, bundle: IngestBundle) -> None:
        """Mirror the bridge's audit trail so dashboards see API runs identically."""
        payload = {
            "sheet_id": bundle.satellite_id,
            "spreadsheet_name": bundle.satellite_name,
            "bridge_version": self.bridge_version,
            "status": "success",
            "tabs_received": list(bundle.tabs.keys()),
            "row_counts": {t: len(v) for t, v in bundle.tabs.items()},
            "source_type": "API_INGEST",
            "logic_engine": "PYTHON_INGEST",
        }
        try:
            self._post("satellite_sync_events", payload)
        except Exception as exc:  # noqa: BLE001 - audit trail is best-effort
            log.warning("sync event not recorded for %s: %s", bundle.satellite_id, exc)


# ─────────────────────────────────────────────────────────────────────────
# Fan-out
# ─────────────────────────────────────────────────────────────────────────

class MultiSink:
    def __init__(self, sinks: List[Any]):
        self.sinks = sinks

    def write(self, bundle: IngestBundle) -> List[Dict[str, Any]]:
        results = []
        for sink in self.sinks:
            try:
                results.append(sink.write(bundle))
            except Exception as exc:  # noqa: BLE001
                log.error("sink '%s' failed for %s: %s", getattr(sink, "name", "?"), bundle.satellite_id, exc)
                results.append({"sink": getattr(sink, "name", "?"), "error": str(exc)})
        return results


def make_sink(name: str, **kwargs: Any):
    if name == "local":
        return LocalBundleSink(**kwargs)
    if name == "supabase":
        return SupabaseSink(**kwargs)
    raise ValueError(f"unknown sink '{name}' — available: local, supabase")


def _safe(text: str) -> str:
    return "".join(ch if ch.isalnum() or ch in "-_." else "_" for ch in text)
